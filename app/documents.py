"""Submission-ready document generation.

Renders collected form data into a clean, printable PDF using reportlab.
The output is designed to look like an official campus form submission:
a header, a reference number, a field table, and a signature block.
"""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from .forms import CAMPUS, FormDefinition


def _reference_number(form_id: str) -> str:
    stamp = datetime.now().strftime("%Y%m%d%H%M%S")
    prefix = "".join(w[0] for w in form_id.split("_")).upper()
    return f"{prefix}-{stamp}"


def generate_pdf(form: FormDefinition, data: dict) -> tuple[bytes, str]:
    """Return (pdf_bytes, reference_number).

    Most forms render as a submission-ready field table. Some forms - like the
    enrollment verification - are official letters and get a dedicated layout.
    """
    if form.id == "enrollment_verification":
        return _generate_enrollment_letter(form, data)
    if form.id == "sap_appeal":
        return _generate_sap_appeal(form, data)
    return _generate_form_pdf(form, data)


def _generate_form_pdf(form: FormDefinition, data: dict) -> tuple[bytes, str]:
    """Return (pdf_bytes, reference_number)."""
    buf = io.BytesIO()
    ref = _reference_number(form.id)

    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        leftMargin=0.9 * inch,
        rightMargin=0.9 * inch,
        title=f"{form.title} - {ref}",
    )

    styles = getSampleStyleSheet()
    h_campus = ParagraphStyle(
        "Campus", parent=styles["Title"], fontSize=18, spaceAfter=2
    )
    h_form = ParagraphStyle(
        "FormTitle",
        parent=styles["Heading2"],
        fontSize=13,
        textColor=colors.HexColor("#334155"),
        spaceAfter=12,
    )
    meta = ParagraphStyle(
        "Meta", parent=styles["Normal"], fontSize=9,
        textColor=colors.HexColor("#64748b"),
    )
    body = styles["Normal"]

    story = []
    story.append(Paragraph(CAMPUS["name"], h_campus))
    story.append(Paragraph(form.title, h_form))
    story.append(
        Paragraph(
            f"Reference: <b>{ref}</b> &nbsp;&nbsp;|&nbsp;&nbsp; "
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            meta,
        )
    )
    story.append(Spacer(1, 0.25 * inch))

    # Field table.
    rows = [["Field", "Response"]]
    for f in form.fields:
        val = data.get(f.key, "")
        if val == "" and not f.required:
            continue
        if isinstance(val, bool):
            val = "Yes" if val else "No"
        label = f.key.replace("_", " ").title()
        rows.append([label, Paragraph(str(val), body)])

    table = Table(rows, colWidths=[2.2 * inch, 4.1 * inch])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [colors.white, colors.HexColor("#f1f5f9")]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 0.4 * inch))

    # Attestation + signature block.
    story.append(
        Paragraph(
            "I certify that the information provided above is accurate and "
            "complete to the best of my knowledge.",
            body,
        )
    )
    story.append(Spacer(1, 0.5 * inch))

    sig = Table(
        [["_______________________________", "_______________________"],
         ["Student Signature", "Date"]],
        colWidths=[3.2 * inch, 2.2 * inch],
    )
    sig.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TEXTCOLOR", (0, 1), (-1, 1), colors.HexColor("#64748b")),
                ("TOPPADDING", (0, 1), (-1, 1), 2),
            ]
        )
    )
    story.append(sig)
    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "This document was generated by the Campus Form Assistant. "
            f"Submit it to the registrar quoting reference {ref}.",
            meta,
        )
    )

    doc.build(story)
    return buf.getvalue(), ref


def _generate_enrollment_letter(form: FormDefinition, data: dict) -> tuple[bytes, str]:
    """Render an official enrollment verification letter.

    Unlike the generic field table, this produces a business-letter layout:
    campus letterhead, date, recipient block, a verification paragraph built
    from the student's official record, and a registrar signature block.
    """
    buf = io.BytesIO()
    ref = _reference_number(form.id)
    today = datetime.now().strftime("%B %d, %Y")

    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        leftMargin=1.0 * inch,
        rightMargin=1.0 * inch,
        title=f"{form.title} - {ref}",
    )

    styles = getSampleStyleSheet()
    h_campus = ParagraphStyle(
        "Campus", parent=styles["Title"], fontSize=18, spaceAfter=2
    )
    office = ParagraphStyle(
        "Office", parent=styles["Normal"], fontSize=10,
        textColor=colors.HexColor("#334155"), spaceAfter=1,
    )
    meta = ParagraphStyle(
        "Meta", parent=styles["Normal"], fontSize=9,
        textColor=colors.HexColor("#64748b"),
    )
    body = ParagraphStyle(
        "LetterBody", parent=styles["Normal"], fontSize=11, leading=16,
        spaceAfter=12,
    )

    story = []

    # Letterhead.
    story.append(Paragraph(CAMPUS["name"], h_campus))
    story.append(Paragraph(CAMPUS.get("registrar_office", "Office of the Registrar"), office))
    story.append(Paragraph(CAMPUS.get("registrar_address", ""), office))
    story.append(Paragraph(CAMPUS.get("registrar_phone", ""), office))
    story.append(Spacer(1, 0.35 * inch))

    # Date + reference.
    story.append(Paragraph(today, body))
    story.append(
        Paragraph(f"Reference: <b>{ref}</b>", meta)
    )
    story.append(Spacer(1, 0.2 * inch))

    # Recipient block.
    recipient = data.get("recipient_name", "To Whom It May Concern")
    story.append(Paragraph(f"To: {recipient}", body))
    story.append(Paragraph("Re: Verification of Student Enrollment", body))
    story.append(Spacer(1, 0.1 * inch))

    # Verification body, built from the official record.
    name = data.get("student_name", "")
    status = data.get("enrollment_status", "")
    credits = data.get("credits_enrolled", "")
    program = data.get("program", "")
    standing = data.get("class_standing", "")
    term = data.get("term", CAMPUS.get("current_term", "the current term"))
    grad = data.get("expected_graduation", "")
    start = data.get("enrollment_start", "")

    story.append(Paragraph("To Whom It May Concern:", body))

    para1 = (
        f"This letter confirms that <b>{name}</b> is currently enrolled as a "
        f"<b>{status}</b> student at {CAMPUS['name']} for the <b>{term}</b> term. "
        f"According to our records, the student is enrolled in <b>{credits} "
        f"credit hours</b> in the <b>{program}</b> program and currently holds "
        f"<b>{standing}</b> class standing."
    )
    story.append(Paragraph(para1, body))

    para2 = (
        f"The student's enrollment at {CAMPUS['name']} began on {start}, and "
        f"their expected graduation is <b>{grad}</b>. This information is "
        f"accurate as of the date of this letter."
    )
    story.append(Paragraph(para2, body))

    para3 = (
        "If you require any additional information or wish to verify the "
        f"authenticity of this letter, please contact the "
        f"{CAMPUS.get('registrar_office', 'Office of the Registrar')} at "
        f"{CAMPUS.get('registrar_phone', '')} and reference the number above."
    )
    story.append(Paragraph(para3, body))

    story.append(Spacer(1, 0.4 * inch))

    # Signature block.
    story.append(Paragraph("Sincerely,", body))
    story.append(Spacer(1, 0.45 * inch))
    story.append(Paragraph("_______________________________", body))
    story.append(Paragraph(
        f"{CAMPUS.get('registrar_office', 'Office of the Registrar')}", office
    ))
    story.append(Paragraph(CAMPUS["name"], office))
    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "This document was generated by the Campus Form Assistant based on "
            f"verified student records. Reference {ref}.",
            meta,
        )
    )

    doc.build(story)
    return buf.getvalue(), ref


def _generate_sap_appeal(form: FormDefinition, data: dict) -> tuple[bytes, str]:
    """Render a completed, submission-ready SAP appeal document.

    Produces a formal appeal: campus header, a details table (student, standard
    failed, term, circumstance, documentation), the student's personal
    statement, what has changed, the academic plan, and a signature block.
    """
    buf = io.BytesIO()
    ref = _reference_number(form.id)
    today = datetime.now().strftime("%B %d, %Y")

    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        leftMargin=1.0 * inch,
        rightMargin=1.0 * inch,
        title=f"{form.title} - {ref}",
    )

    styles = getSampleStyleSheet()
    h_campus = ParagraphStyle(
        "Campus", parent=styles["Title"], fontSize=18, spaceAfter=2
    )
    h_form = ParagraphStyle(
        "FormTitle", parent=styles["Heading2"], fontSize=13,
        textColor=colors.HexColor("#334155"), spaceAfter=10,
    )
    section = ParagraphStyle(
        "Section", parent=styles["Heading3"], fontSize=11,
        textColor=colors.HexColor("#1e293b"), spaceBefore=10, spaceAfter=4,
    )
    meta = ParagraphStyle(
        "Meta", parent=styles["Normal"], fontSize=9,
        textColor=colors.HexColor("#64748b"),
    )
    body = ParagraphStyle(
        "Body", parent=styles["Normal"], fontSize=11, leading=16, spaceAfter=8,
    )

    story = []
    story.append(Paragraph(CAMPUS["name"], h_campus))
    story.append(Paragraph(form.title, h_form))
    story.append(
        Paragraph(
            f"Reference: <b>{ref}</b> &nbsp;&nbsp;|&nbsp;&nbsp; "
            f"Date: {today}",
            meta,
        )
    )
    story.append(Spacer(1, 0.25 * inch))

    # Details table.
    doc_text = "Yes" if data.get("has_documentation") else "No"
    rows = [
        ["Student Name", data.get("student_name", "")],
        ["Student ID", data.get("student_id", "")],
        ["Campus Email", data.get("email", "")],
        ["SAP Standard Not Met", data.get("standard_failed", "")],
        ["Term Affected", data.get("term_affected", "")],
        ["Extenuating Circumstance", data.get("circumstance", "")],
        ["Supporting Documentation Attached", doc_text],
    ]
    table = Table(
        [[Paragraph(f"<b>{k}</b>", body), Paragraph(str(v), body)] for k, v in rows],
        colWidths=[2.6 * inch, 3.7 * inch],
    )
    table.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ROWBACKGROUNDS", (0, 0), (-1, -1),
                 [colors.white, colors.HexColor("#f1f5f9")]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(table)

    # Narrative sections.
    story.append(Paragraph("Personal Statement", section))
    story.append(Paragraph(_escape(data.get("personal_statement", "")), body))

    story.append(Paragraph("What Has Changed", section))
    story.append(Paragraph(_escape(data.get("whats_changed", "")), body))

    story.append(Paragraph("Academic Plan Going Forward", section))
    story.append(Paragraph(_escape(data.get("academic_plan", "")), body))

    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "I certify that the information in this appeal is true and complete "
            "to the best of my knowledge, and I understand that supporting "
            "documentation may be required before a decision is made.",
            body,
        )
    )
    story.append(Spacer(1, 0.5 * inch))

    sig = Table(
        [["_______________________________", "_______________________"],
         ["Student Signature", "Date"]],
        colWidths=[3.2 * inch, 2.2 * inch],
    )
    sig.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TEXTCOLOR", (0, 1), (-1, 1), colors.HexColor("#64748b")),
                ("TOPPADDING", (0, 1), (-1, 1), 2),
            ]
        )
    )
    story.append(sig)
    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "This appeal was prepared with the Campus Form Assistant. Submit it "
            f"to the Office of Financial Aid quoting reference {ref}. Attach any "
            "supporting documentation before submitting.",
            meta,
        )
    )

    doc.build(story)
    return buf.getvalue(), ref


def _escape(text: str) -> str:
    """Escape user text for reportlab Paragraph and preserve line breaks."""
    text = (text or "")
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return text.replace("\n", "<br/>")
