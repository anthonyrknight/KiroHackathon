"""Submission-ready document generation.

Renders collected form data into a clean, printable PDF using reportlab.
The output is designed to look like an official campus form submission:
a header, a reference number, a field table, and a signature block.
"""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from .forms import CAMPUS, FormDefinition


def _reference_number(form_id: str) -> str:
    stamp = datetime.now().strftime("%Y%m%d%H%M%S")
    prefix = "".join(w[0] for w in form_id.split("_")).upper()
    return f"{prefix}-{stamp}"


def generate_pdf(form: FormDefinition, data: dict) -> tuple[bytes, str]:
    """Return (pdf_bytes, reference_number)."""
    buf = io.BytesIO()
    ref = _reference_number(form.id)

    doc = SimpleDocTemplate(
        buf,
        pagesize=LETTER,
        topMargin=0.9 * inch,
        bottomMargin=0.9 * inch,
        leftMargin=0.9 * inch,
        rightMargin=0.9 * inch,
        title=f"{form.title} - {ref}",
    )

    styles = getSampleStyleSheet()
    h_campus = ParagraphStyle(
        "Campus", parent=styles["Title"], fontSize=18, spaceAfter=2
    )
    h_form = ParagraphStyle(
        "FormTitle",
        parent=styles["Heading2"],
        fontSize=13,
        textColor=colors.HexColor("#334155"),
        spaceAfter=12,
    )
    meta = ParagraphStyle(
        "Meta", parent=styles["Normal"], fontSize=9,
        textColor=colors.HexColor("#64748b"),
    )
    body = styles["Normal"]

    story = []
    story.append(Paragraph(CAMPUS["name"], h_campus))
    story.append(Paragraph(form.title, h_form))
    story.append(
        Paragraph(
            f"Reference: <b>{ref}</b> &nbsp;&nbsp;|&nbsp;&nbsp; "
            f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            meta,
        )
    )
    story.append(Spacer(1, 0.25 * inch))

    # Field table.
    rows = [["Field", "Response"]]
    for f in form.fields:
        val = data.get(f.key, "")
        if val == "" and not f.required:
            continue
        if isinstance(val, bool):
            val = "Yes" if val else "No"
        label = f.key.replace("_", " ").title()
        rows.append([label, Paragraph(str(val), body)])

    table = Table(rows, colWidths=[2.2 * inch, 4.1 * inch])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e293b")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [colors.white, colors.HexColor("#f1f5f9")]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 0.4 * inch))

    # Attestation + signature block.
    story.append(
        Paragraph(
            "I certify that the information provided above is accurate and "
            "complete to the best of my knowledge.",
            body,
        )
    )
    story.append(Spacer(1, 0.5 * inch))

    sig = Table(
        [["_______________________________", "_______________________"],
         ["Student Signature", "Date"]],
        colWidths=[3.2 * inch, 2.2 * inch],
    )
    sig.setStyle(
        TableStyle(
            [
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TEXTCOLOR", (0, 1), (-1, 1), colors.HexColor("#64748b")),
                ("TOPPADDING", (0, 1), (-1, 1), 2),
            ]
        )
    )
    story.append(sig)
    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            "This document was generated by the Campus Form Assistant. "
            f"Submit it to the registrar quoting reference {ref}.",
            meta,
        )
    )

    doc.build(story)
    return buf.getvalue(), ref
